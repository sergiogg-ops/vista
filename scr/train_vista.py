from configargparse import ArgumentParser
import os
import random
import yaml
from typing import Union
import numpy as np
import pytorch_lightning as pl
import torch
from pytorch_lightning.callbacks import ModelCheckpoint, EarlyStopping, Callback
from lightning.pytorch.loggers import WandbLogger
from transformers import (
    AutoModelForSeq2SeqLM, 
    NllbTokenizer, 
    AutoModelForImageTextToText)
from peft import LoraConfig, get_peft_model
import vista as mt
from dotenv import load_dotenv

load_dotenv()
HF_TOKEN = os.getenv("HF_TOKEN")
torch.cuda.init()
torch.cuda.set_device(0)
_ = torch.zeros(1).cuda()


class PatienceLogger(Callback):
    """Logs the EarlyStopping patience counter after every validation epoch."""

    def __init__(self, early_stopping_callback: EarlyStopping):
        self.es = early_stopping_callback

    def on_validation_epoch_end(self, trainer, pl_module):
        pl_module.log("patience", float(self.es.wait_count), prog_bar=True)

def int_or_float(value: str) -> Union[int, float]:
    try:
        return int(value)
    except ValueError:
        return float(value)

def parse_args():
    # First parse only --config so the YAML file can be loaded manually.
    config_parser = ArgumentParser(add_help=False)
    config_parser.add_argument("--config", type=str, help="Path to config file.")
    config_args, _ = config_parser.parse_known_args()

    parser = ArgumentParser()
    parser.add_argument("--config", type=str, help="Path to config file.")
    parser.add_argument("--project", type=str, default='debug', help="Name of the project into which include the WandB run")
    parser.add_argument("--vision_model", type=str, default='google/siglip2-base-patch16-naflex', help="Path to pretrained vision model.")
    parser.add_argument("--mt_model_path", type=str, default='black-forest-labs/FLUX.2-klein-4B', help="Path to pretrained MT model.")
    parser.add_argument("--train_latents_dir", type=str, help="Directory containing precomputed training latents.")
    parser.add_argument("--valid_latents_dir", type=str, help="Directory containing precomputed validation latents.")
    parser.add_argument("--distilling", action='store_true', help="Whether to use the translations generated by the same model as targets for training.")
    parser.add_argument("--src_lang", type=str, help="Source language token (e.g., <eng_Latn> for English).")
    parser.add_argument("--tgt_langs", type=str, nargs='+', help="Target language tokens (e.g., <zho_Hans> for Chinese).")
    parser.add_argument("--monitor_metric", type=str, default="val_fid", help="Metric to monitor for model checkpointing and early stopping.")
    parser.add_argument("--monitor_mode", type=str, default="min", choices=["min", "max"], help="Whether to minimize or maximize the monitored metric.")
    parser.add_argument("--save", type=str, default='checkpoints', help="Directory to save model checkpoints.")
    parser.add_argument("--name", type=str, default='mt_experiment', help="Name of the experiment (used for logging).")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility.")
    parser.add_argument("--num_workers", type=int, default=1, help="Number of workers for the data loading")
    parser.add_argument("--train_batch_size", type=int, default=8)
    parser.add_argument("--val_batch_size", type=int, default=8)
    parser.add_argument("--accumulate_grad", type=int, default=1, help="Number of steps to accumulate gradients before updating model parameters.")
    parser.add_argument("--max_epochs", type=int, default=None)
    parser.add_argument("--max_steps", type=int, default=-1, help="Maximum number of training steps (overrides max_epochs if set).")
    parser.add_argument("--val_check_interval", default=5000, type=int_or_float, help="Number of training steps between validation checks.")
    parser.add_argument("--unfreeze_milestones", type=int, nargs='+', default=[-1,-1,-1], help="Amount of steps before unfreezing the decoder cross attention, the decoder top 2 layers and the decoder top 4 layers.")
    parser.add_argument("--ini_lr", type=float, default=3e-5, help="Initial learning rate.")
    parser.add_argument("--lr_decoder", type=float, default=3e-6, help="Initial learning rate for the decoder.")
    parser.add_argument("--lr_vision", type=float, default=3e-6, help="Initial learning rate for the vision model.")
    parser.add_argument("--min_lr", type=float, default=1e-6, help="Minimum learning rate.")
    parser.add_argument("--mt_weight", type=float, default=1.0, help="Main MT loss weight")
    parser.add_argument("--ctc_weight", type=float, default=1.0, help="Auxiliar CTC loss weight")
    parser.add_argument("--align_weight", type=float, default=1.0, help="Alignment loss weight")
    parser.add_argument("--adapter_args", type=dict, default={"visual_hidden_size":768, "text_hidden_size":1024}, help="Keyword arguments for the image adapter")
    parser.add_argument("--use_lora", action="store_true", help="Enable LoRA fine-tuning")
    parser.add_argument("--lora_r", type=int, default=8)
    parser.add_argument("--lora_alpha", type=int, default=16)
    parser.add_argument("--lora_dropout", type=float, default=0.1)
    parser.add_argument("--early_stopping", action="store_true", help="Enable early stopping")
    parser.add_argument("--patience", type=int, help="Early stopping patience epochs", default=3)
    parser.add_argument("--checkpointing", action="store_true", help="Enable checkpointing")
    parser.add_argument("--flash_attn", action="store_true", help="Enable Flash Attention implementation")

    if config_args.config is not None:
        with open(config_args.config, 'r') as f:
            config = yaml.safe_load(f) or {}
        parser.set_defaults(**config)

    return parser.parse_args()

def seed_everything(seed: int, deterministic: bool = True):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    if deterministic:
        torch.use_deterministic_algorithms(True)

def freeze_params(model):
    for name, param in model.named_parameters():
        if param.requires_grad:
            param.requires_grad = False

def main():
    args = parse_args()
    seed_everything(args.seed)
    pl.seed_everything(args.seed, workers=True)
    kwargs = {"attn_implementation":"flash_attention_2", "dtype":torch.float16} if args.flash_attn else {}
    mt_model = AutoModelForSeq2SeqLM.from_pretrained(args.mt_model_path, 
                                                        token=HF_TOKEN, 
                                                        use_safetensors=True,
                                                        **kwargs)
    vision_model = AutoModelForImageTextToText.from_pretrained(args.vision_model, 
                                                  token=HF_TOKEN, 
                                                  use_safetensors=True).model.visual.vision_model
    if args.use_lora:
        lora_config = LoraConfig(
            r=args.lora_r,
            lora_alpha=args.lora_alpha,
            lora_dropout=args.lora_dropout,
            target_modules=["k_proj", "q_proj", "v_proj", "out_proj", "fc1", "fc2"]
        )
        vision_model = get_peft_model(vision_model, lora_config)
    freeze_params(mt_model)
    freeze_params(vision_model)
    # Language tokens
    tokenizer = NllbTokenizer.from_pretrained(args.mt_model_path, 
                                                    token=HF_TOKEN,
                                                    src_lang=args.src_lang,
                                                    tgt_lang=args.tgt_langs,)

    padding_tok = tokenizer.pad_token_id
    model = mt.Translator(mt_model=mt_model,
                          vision_encoder=vision_model,
                          tokenizer=tokenizer,
                          src_lang=args.src_lang,
                          tgt_langs=args.tgt_langs,
                          encoder_lr=args.lr_vision,
                          adapter_lr=args.ini_lr,
                          decoder_lr=args.lr_decoder,
                          min_lr=args.min_lr,
                          max_steps=args.max_steps,
                          step_milestones=args.unfreeze_milestones,
                          mt_loss=args.mt_weight,
                          ctc_loss=args.ctc_weight,
                          padding_value=padding_tok,
                          flash_attn=args.flash_attn,
                          adapter_args=args.adapter_args)
    data_module = mt.MTDataModule(train_data_dir=args.train_latents_dir,
                                 val_data_dir=args.valid_latents_dir,
                                 pad_token_id=padding_tok,
                                 #add_synthetic=args.distilling,
                                 train_batch_size=args.train_batch_size,
                                 val_batch_size=args.val_batch_size,
                                 num_workers=args.num_workers,
                                 tgt_langs=args.tgt_langs)

    callbacks = []
    if args.checkpointing:
        checkpoint_callback = ModelCheckpoint(
            dirpath=args.save,
            filename= args.name + "-{step}-{val_BLEU:.4f}",
            save_top_k=3,
            monitor='val_BLEU',
            mode='max',
        )
        callbacks.append(checkpoint_callback)
    if args.early_stopping:
        es_callback = EarlyStopping(monitor=args.monitor_metric, mode=args.monitor_mode, patience=args.patience)
        callbacks.append(es_callback)
        callbacks.append(PatienceLogger(es_callback))
    logger = WandbLogger(
        save_dir=args.save,
        name=args.name,
        project=args.project
    )

    trainer = pl.Trainer(
        accelerator='gpu',
        default_root_dir=args.save,
        max_epochs=args.max_epochs,
        max_steps=args.max_steps,
        callbacks=callbacks,
        gradient_clip_val=1.0,
        val_check_interval=args.val_check_interval,
        logger=logger,
        num_sanity_val_steps=2,
        accumulate_grad_batches=args.accumulate_grad,
        #enable_progress_bar=False,
        deterministic='warn',
        benchmark=False,

    )

    #trainer.validate(model, datamodule=data_module)
    trainer.fit(model, data_module)
    if args.checkpointing:
        print(f"Best model saved at: {checkpoint_callback.best_model_path}")

if __name__ == "__main__":
    main()
